import {
  Bucket,
  Cover,
  ParentRequest,
  PendingWant,
  PurchaseVerdict,
  Transaction,
  Trip,
  SAVINGS_BUCKET_ID,
  initialBuckets,
} from "@/lib/bucket-store";

/**
 * Everything that is genuinely *about the money*. This object is the unit of
 * persistence in Phase 2, so it must stay JSON-serializable: no React components,
 * no DOM nodes, no functions.
 *
 * Presentation state (which tab is open, whether a coin is mid-flight, which card is
 * pulsing) deliberately lives outside this, in the provider. Mixing it in is what makes
 * a store impossible to write to a database.
 */
export type BucketState = {
  buckets: Bucket[];
  startingBalances: Record<string, number>;
  transactions: Transaction[];
  /** Money moved between buckets to clear a negative. Never read by the engine. */
  covers: Cover[];
  pending: PendingWant[];
  parentRequests: ParentRequest[];
  savedByPause: number;
  trip: Trip | null;
};

export const createInitialState = (): BucketState => ({
  buckets: initialBuckets,
  startingBalances: Object.fromEntries(initialBuckets.map((b) => [b.id, b.balance])),
  transactions: [],
  covers: [],
  pending: [],
  parentRequests: [],
  savedByPause: 0,
  trip: null,
});

/**
 * Actions carry fully-formed records. Ids and timestamps are generated by the caller,
 * never in here — a reducer that reads `crypto.randomUUID()` or the clock cannot be
 * replayed against a fixture, which is exactly what the Phase 8 evaluation set needs.
 */
export type BucketAction =
  | { type: "HYDRATE"; state: BucketState }
  | { type: "RESET" }
  | { type: "CONFIRM_PURCHASE"; transaction: Transaction }
  | { type: "SLEEP_ON_IT"; item: PendingWant }
  | { type: "REMOVE_PENDING"; id: string }
  | { type: "RESTORE_PENDING"; item: PendingWant }
  | { type: "CREDIT_SAVINGS"; amount: number }
  | { type: "DEBIT_SAVINGS"; amount: number }
  | { type: "CREATE_BUCKET"; bucket: Bucket }
  | { type: "SET_CHILD_LIMIT"; limit: number | null }
  | { type: "PARENT_REQUEST_CREATE"; request: ParentRequest }
  | { type: "PARENT_REQUEST_RESOLVE"; id: string; status: "approved" | "denied" }
  | { type: "SET_TRIP"; trip: Trip | null }
  | { type: "ATTACH_VERDICT"; subjectId: string; verdict: PurchaseVerdict }
  | { type: "RETRACT_TO_TRAY"; transactionId: string; pendingId: string; createdAt: number }
  | { type: "OVERRIDE_VERDICT"; transactionId: string }
  | { type: "COVER_BUCKET"; cover: Cover }
  | { type: "ATTACH_RECONSIDERATION"; transactionId: string; verdict: PurchaseVerdict };

export function bucketReducer(state: BucketState, action: BucketAction): BucketState {
  switch (action.type) {
    case "HYDRATE":
      return action.state;

    case "RESET":
      return createInitialState();

    case "CONFIRM_PURCHASE": {
      const { transaction } = action;
      return {
        ...state,
        buckets: state.buckets.map((b) =>
          b.id === transaction.bucketId ? { ...b, balance: b.balance - transaction.amount } : b,
        ),
        transactions: [transaction, ...state.transactions],
      };
    }

    case "SLEEP_ON_IT":
      return { ...state, pending: [action.item, ...state.pending] };

    case "REMOVE_PENDING":
      return { ...state, pending: state.pending.filter((p) => p.id !== action.id) };

    case "RESTORE_PENDING":
      return { ...state, pending: [action.item, ...state.pending] };

    /**
     * Releasing a pending want. `startingBalances` moves in step with the balance so the
     * Savings card does not read the incoming money as "spent" on its progress bar.
     */
    case "CREDIT_SAVINGS":
      return {
        ...state,
        buckets: state.buckets.map((b) =>
          b.id === SAVINGS_BUCKET_ID ? { ...b, balance: b.balance + action.amount } : b,
        ),
        startingBalances: {
          ...state.startingBalances,
          [SAVINGS_BUCKET_ID]: (state.startingBalances[SAVINGS_BUCKET_ID] ?? 0) + action.amount,
        },
        savedByPause: state.savedByPause + action.amount,
      };

    /** Undo of the above. The clamps match the prototype's behaviour exactly. */
    case "DEBIT_SAVINGS":
      return {
        ...state,
        buckets: state.buckets.map((b) =>
          b.id === SAVINGS_BUCKET_ID ? { ...b, balance: b.balance - action.amount } : b,
        ),
        startingBalances: {
          ...state.startingBalances,
          [SAVINGS_BUCKET_ID]: Math.max(
            0,
            (state.startingBalances[SAVINGS_BUCKET_ID] ?? 0) - action.amount,
          ),
        },
        savedByPause: Math.max(0, state.savedByPause - action.amount),
      };

    /**
     * Clearing a negative by moving money out of a bucket that has it.
     *
     * `startingBalances` is deliberately left alone, which is what makes both cards read
     * honestly afterwards. The funding bucket's spend grows, because the money really did
     * leave it. The covered bucket returns to the zero it started at, so it reads $0 with
     * nothing spent rather than carrying a phantom credit.
     *
     * Rejected rather than clamped when the numbers do not work: a clamp would record a
     * {@link Cover} row stating an amount that differs from what actually moved, and that
     * row is the only audit trail reconciling a funding bucket's card against its ledger.
     * Covering more than the deficit is refused too, since overshooting re-creates the
     * slush fund the empty bucket exists to prevent.
     */
    case "COVER_BUCKET": {
      const { cover } = action;
      const from = state.buckets.find((b) => b.id === cover.fromBucketId);
      const to = state.buckets.find((b) => b.id === cover.toBucketId);

      if (!from || !to || from.id === to.id) return state;
      if (!(cover.amount > 0)) return state;
      if (cover.amount > from.balance) return state;
      if (cover.amount > -to.balance) return state;

      return {
        ...state,
        buckets: state.buckets.map((b) => {
          if (b.id === from.id) return { ...b, balance: b.balance - cover.amount };
          if (b.id === to.id) return { ...b, balance: b.balance + cover.amount };
          return b;
        }),
        covers: [cover, ...state.covers],
      };
    }

    case "CREATE_BUCKET":
      return {
        ...state,
        buckets: [...state.buckets, action.bucket],
        startingBalances: {
          ...state.startingBalances,
          [action.bucket.id]: action.bucket.balance,
        },
      };

    case "SET_CHILD_LIMIT":
      return {
        ...state,
        buckets: state.buckets.map((b) =>
          b.ownerType === "child" ? { ...b, limit: action.limit } : b,
        ),
      };

    case "PARENT_REQUEST_CREATE":
      return { ...state, parentRequests: [action.request, ...state.parentRequests] };

    case "PARENT_REQUEST_RESOLVE":
      return {
        ...state,
        parentRequests: state.parentRequests.map((r) =>
          r.id === action.id ? { ...r, status: action.status } : r,
        ),
      };

    case "SET_TRIP":
      return { ...state, trip: action.trip };

    /**
     * A verdict arriving after the fact.
     *
     * The model call is fired without being awaited, so by the time it lands the item may
     * have moved, been released, or been undone. Matching on id across both collections and
     * silently doing nothing when it is gone is the correct behaviour, not an error case.
     */
    case "ATTACH_VERDICT": {
      const { subjectId, verdict } = action;
      return {
        ...state,
        transactions: state.transactions.map((t) => (t.id === subjectId ? { ...t, verdict } : t)),
        pending: state.pending.map((p) => (p.id === subjectId ? { ...p, verdict } : p)),
      };
    }

    /**
     * Bucket's answer to an explanation, kept beside the verdict it answers.
     *
     * Deliberately not an overwrite. The card shows the original argument and what became of
     * it, so replacing the verdict would leave a person reading a conclusion with no record
     * of what it concluded about, and would erase the disagreement from the stored history
     * whenever the person talked Bucket out of it. Those are exactly the cases worth keeping.
     *
     * Only logged purchases are reconsidered. A tray item is already paused, so there is
     * nothing to argue about yet.
     */
    case "ATTACH_RECONSIDERATION": {
      const { transactionId, verdict } = action;
      return {
        ...state,
        transactions: state.transactions.map((t) =>
          t.id === transactionId ? { ...t, reconsideration: verdict } : t,
        ),
      };
    }

    /**
     * The person accepted Bucket's second thought and pulled a logged purchase back.
     *
     * The money returns to its bucket and the item moves into the Sleep On It tray, which is
     * where undecided things live. This is only ever reached from an explicit button press —
     * Bucket offers, it never retracts a purchase on its own.
     */
    case "RETRACT_TO_TRAY": {
      const tx = state.transactions.find((t) => t.id === action.transactionId);
      if (!tx) return state;

      return {
        ...state,
        buckets: state.buckets.map((b) =>
          b.id === tx.bucketId ? { ...b, balance: b.balance + tx.amount } : b,
        ),
        // The transaction is removed rather than flagged: the purchase did not happen yet.
        // The decision itself survives on the pending item, which carries the verdict.
        transactions: state.transactions.filter((t) => t.id !== action.transactionId),
        pending: [
          {
            id: action.pendingId,
            amount: tx.amount,
            label: tx.label,
            bucketId: tx.bucketId,
            createdAt: action.createdAt,
            hoursLeft: 23,
            intent: tx.intent,
            readinessTag: tx.readinessTag,
            verdict: tx.verdict ?? null,
          },
          ...state.pending,
        ],
      };
    }

    /** The person considered the argument and kept their own call. Both are recorded. */
    case "OVERRIDE_VERDICT":
      return {
        ...state,
        transactions: state.transactions.map((t) =>
          t.id === action.transactionId ? { ...t, verdictResponse: "overridden" } : t,
        ),
      };

    default:
      return state;
  }
}
